import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const [sourceArg,outputArg]=process.argv.slice(2);
if(!sourceArg||!outputArg)throw Error('Usage: node prepare.mjs AUDIO_RUN OUTPUT_DIR');
const source=resolve(sourceArg),out=join(resolve(outputArg),'app'),here=dirname(fileURLToPath(import.meta.url));
const receipt=JSON.parse(await readFile(join(source,'receipt.json'),'utf8'));
const data=JSON.parse(await readFile(join(source,'timestamps.json'),'utf8'));
if(data.segments?.length!==1)throw Error('This bench requires one audio segment with real alignment; no guessed offsets');
const a=data.segments[0].alignment;
if(a.status!=='aligned'||a.unit!=='seconds'||!a.words?.length||!Number.isFinite(a.duration_seconds))throw Error('Real alignment unavailable');
const audio=await readFile(join(source,receipt.file));
if(createHash('sha256').update(audio).digest('hex')!==receipt.sha256)throw Error('Audio receipt mismatch');
if(receipt.file!=='audio.wav')throw Error('WAV fixture required');
await mkdir(out,{recursive:true,mode:0o700});
for(const name of ['index.html','renderer.mjs','sync.mjs'])await copyFile(join(here,name),join(out,name));
await writeFile(join(out,'audio.wav'),audio,{mode:0o600});
await writeFile(join(out,'fixture.js'),'window.fixture='+JSON.stringify({words:a.words,duration:a.duration_seconds,generatedAt:receipt.completedAt,audioSha256:receipt.sha256})+';\n',{mode:0o600});
console.log(JSON.stringify({out,words:a.words.length,duration:a.duration_seconds,audioVerified:true}));
